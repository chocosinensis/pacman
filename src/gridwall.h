static inline bool IsWall(float x, float y) {
    int gridX = (int)(x / GRID_LENGTH);
    int gridY = (int)(y / GRID_LENGTH);

    if (gridX < 0 || gridX >= GRID_WIDTH || gridY < 0 || gridY >= GRID_HEIGHT) {
        return false;
    }

    return MAP[gridY][gridX] == 1;
}